/** Generate the startup preparation list from the checked-in, signed Windows catalog. */
import fs from "node:fs/promises";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";

const root = fileURLToPath(new URL("..", import.meta.url));
const content = await fs.readFile(path.join(root, "backend/src/modules/components/catalog.generated.ts"), "utf8");
const start = content.indexOf("{", content.indexOf("export const packagedComponentCatalog ="));
const catalog = JSON.parse(content.slice(start, content.lastIndexOf("}") + 1));
const order = [
  "python-312",
  "ffmpeg",
  "edge-tts",
  "image-ai",
  "chatterbox",
  "xhs-browser",
  "xhs-archive",
  "xhs-translation",
  "douyin-archive",
  "chatterbox-cuda"
];
function stable(value) {
  if (Array.isArray(value)) return `[${value.map(stable).join(",")}]`;
  if (value && typeof value === "object")
    return `{${Object.keys(value)
      .sort()
      .map((key) => `${JSON.stringify(key)}:${stable(value[key])}`)
      .join(",")}}`;
  return JSON.stringify(value);
}
const components = order.map((id) => {
  const manifest = catalog.manifests.find((item) => item.id === id);
  if (!manifest) throw new Error(`Missing signed manifest ${id}`);
  const { signature, ...unsigned } = manifest;
  const canonical = stable(unsigned);
  if (
    !crypto.verify(
      null,
      Buffer.from(canonical),
      catalog.trustedPublicKeys[manifest.keyId],
      Buffer.from(signature, "base64")
    )
  )
    throw new Error(`Invalid manifest signature ${id}`);
  return {
    id,
    displayName: manifest.displayName,
    version: manifest.version,
    required: id !== "chatterbox-cuda",
    manifestSha256: crypto.createHash("sha256").update(canonical).digest("hex"),
    archives: [manifest.archive, ...(manifest.additionalArchives ?? [])].map((asset) => ({
      filename: decodeURIComponent(path.posix.basename(new URL(asset.url).pathname)),
      bytes: asset.bytes,
      sha256: asset.sha256,
      url: asset.url
    }))
  };
});
const plan = {
  schemaVersion: 1,
  directory: "offline-resources/components",
  releasePage: "https://github.com/sunshine-tmy/tool2.0/releases/tag/components-v1",
  bootstrap: [
    {
      filename: "node-v24.22.1-win-x64.zip",
      url: "https://nodejs.org/dist/v24.22.1/node-v24.22.1-win-x64.zip",
      algorithm: "SHA256",
      digest: "d2046d28c2c3dcd211ac5145c0bf30e2047ef9dfb306693c8c6e2eccd8b95fa5"
    },
    {
      filename: "pnpm-11.7.0.tgz",
      url: "https://registry.npmjs.org/pnpm/-/pnpm-11.7.0.tgz",
      algorithm: "SHA512",
      digest: "GcyFLBIMcSV2DyRD7mvgyltA+fUFmN4aCaHxd1A+AQ5Xwjx3ZG4B52HeWb+HT7IqM5jDOrlpH8E+uUa28PTWIA=="
    }
  ],
  components
};
const rows = components.map((item) => {
  const archives = item.archives
    .map((file) => `- [${file.filename}](${file.url})（${(file.bytes / 1024 ** 2).toFixed(1)} MiB）`)
    .join("\n");
  const usage = item.required
    ? ""
    : "\n\n以下 4 个归档是 11 个 CPU 基础归档之外的 GPU 扩展，共需准备 15 个文件。文件放入同一目录后，双击根目录 `start-gpu.bat`，或执行 `start.bat -WithCuda`；仅放入包但双击普通 `start.bat` 不会安装 GPU 扩展。可用 `start-gpu.bat -ListResources` 列出完整清单。已有实例须先通过 `stop.bat` 正常停止，已安装且正常的 CPU 能力及模型会复用。需要兼容的 NVIDIA 显卡和驱动，不自动修改驱动；安装包通过校验不等于 GPU 实际生成已验证。此扩展仅加速参考音色克隆，不改变 CPU 图片能力。";
  return `### ${item.displayName}${item.required ? "" : "（可选，仅 -WithCuda）"}\n\n版本：\`${item.version}\`。将以下文件**全部**放到项目根目录的 \`offline-resources/components/\`，保持文件名，不解压：\n\n${archives}${usage}`;
});
const documentation = `<!-- Generated by scripts/generate-source-resources.mjs; do not edit package versions here. -->\n# 新电脑启动：离线资源下载清单\n\n本清单对应当前源码内置的签名版本，不依赖旧项目。CPU 基线共 9 项能力、11 个归档；CUDA 扩展另有 4 个归档，默认不需要。下载可使用浏览器或可信下载工具，下载完可复用，不必每次启动重下。\n\n[全部能力包发布页](${plan.releasePage})。不要下载 Source code ZIP 代替能力包，也不要单独下载另一版本的 Python、模型或 wheel；所需 Python、模型和离线依赖已包含在能力包中。\n\n普通源码依赖允许由 pnpm 联网安装，本清单不保证所有安装和在线业务都能断网完成。\n\n## 可选：提前准备 Node 和 pnpm\n\n已有 Node 24 x64 时自动复用。其余工具会优先检查 \`offline-resources/bootstrap/\`；没有本地压缩包才尝试固定来源下载。可提前下载：\n\n${plan.bootstrap.map((item) => `- [${item.filename}](${item.url})`).join("\n")}\n\n压缩包保持原名、不解压；旧 \`.runtime/bootstrap\` 缓存仍可复用。\n\n## 必备 CPU 能力与可选 GPU 能力\n\n${rows.join("\n\n")}\n\n## 复用旧备份\n\n也支持将按 \`能力ID/版本/文件名\` 组织的完整离线包直接复制到 \`offline-resources/components/\` 下。只识别本清单要求的版本，不自动搜索其他磁盘。不要复制旧虚拟环境、原电脑的 node_modules 或带绝对路径的已安装运行目录。新电脑会从包内 wheelhouse 重建环境，不需要迁移旧 Python 3.11。私钥与平台登录态不是启动前提，不要放进离线资源目录。\n\n启动时缺失或大小不符的文件会一次列出；摘要、签名及文件清单由原能力管理器在安装时校验，错误文件不会改走网络重下或跳过校验。完整下载包会保留供再次安装使用。\n`;
const outputs = [
  ["scripts/source-resources.generated.json", JSON.stringify(plan, null, 2) + "\n"],
  [
    "docs/source-resources.md",
    await format(documentation, { ...(await resolveConfig(path.join(root, "README.md"))), parser: "markdown" })
  ]
];
for (const [relative, expected] of outputs) {
  const file = path.join(root, relative);
  if (process.argv.includes("--check")) {
    if ((await fs.readFile(file, "utf8")) !== expected)
      throw new Error(`Outdated resource list: ${relative}. Run node scripts/generate-source-resources.mjs`);
  } else await fs.writeFile(file, expected);
}
console.log(
  process.argv.includes("--check")
    ? "Source resource list matches the signed catalog."
    : "Source resource list and download guide generated."
);
