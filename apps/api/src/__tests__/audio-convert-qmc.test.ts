import { createHash } from "node:crypto";
import { expect, it } from "vitest";
import { deriveQmcKey, qmcPayload, qmcTransform } from "../domains/audio-convert/qmc";
// Synthetic EncV1/EncV2 vectors generated independently with a Python TEA encoder.
it.each([
  "AQIDBAUGBwjiLgECNOB6pYvsV/gJCEz8+6JjQczvCMi4wdSQPrn253rcQ6BLcl5V",
  "UVFNdXNpYyBFbmNWMixLZXk6c2H3o7hE4rOW5WzhONoGH1PxsjAweSouQHcSvcgZuK8lnN9wzqVcwvn0+9Iiqc0+9DWV8EzP8bQp7wYCbNPgA7CBaoKe1mHSQOxPGQFMgob+AQbC9EFKzP1IsS9LbqbW"
])("unwraps an encoded per-file EKey without treating it as raw key bytes", (encoded) => {
  expect(deriveQmcKey(encoded)).toEqual(Buffer.from(Array.from({ length: 32 }, (_, i) => i + 1)));
});
// Golden hashes computed by the original MIT Python implementation; not generated by this port.
it.each([
  [256, "055655d4f1554e2128d9a34e188525ee529c13d2c64fa8d78f4784b576be4af5"],
  [512, "c19794756c3cc173fc1b8d81312ab74f1553d07dbb9c911a1c1f6fb85ddf4814"]
] as const)("matches QMC reference vectors and arbitrary chunk offsets (%i)", (length, expected) => {
  const key = Buffer.from(Array.from({ length }, (_, i) => (i * 17 + 9) % 256));
  const plain = Buffer.from(Array.from({ length: 18000 }, (_, i) => (i * 13 + 7) % 256));
  const data = Buffer.from(plain);
  qmcTransform(data, key);
  expect(createHash("sha256").update(data).digest("hex")).toBe(expected);
  for (let i = 0; i < data.length; i += 333) qmcTransform(data.subarray(i, i + 333), key, i);
  expect(data).toEqual(plain);
});
it("detects musicex V1 without reading account data and requires per-file EKey", () => {
  const tail = Buffer.alloc(192);
  tail.writeUInt32LE(192, 176);
  tail.writeUInt32LE(1, 180);
  tail.write("musicex\0", 184);
  expect(() => qmcPayload(tail, 1000)).toThrow(expect.objectContaining({ code: "AUDIO_CONVERT_KEY_REQUIRED" }));
  const key = Buffer.alloc(32, 17),
    result = qmcPayload(tail, 1000, key.toString("base64"));
  expect(result.end).toBe(808);
  expect(result.key).toEqual(key);
  tail.writeUInt32LE(2, 180);
  expect(() => qmcPayload(tail, 1000, "key")).toThrow(
    expect.objectContaining({ code: "AUDIO_CONVERT_VERSION_UNSUPPORTED" })
  );
});
it("extracts embedded legacy EKey and rejects corrupt footer bounds", () => {
  const key = Buffer.alloc(32, 17).toString("base64"),
    footer = Buffer.alloc(4);
  footer.writeUInt32LE(key.length);
  const tail = Buffer.concat([Buffer.from("payload"), Buffer.from(key), footer]);
  expect(qmcPayload(tail, tail.length).end).toBe(7);
  const tagged = Buffer.concat([Buffer.from(`${key},123,2`), Buffer.alloc(8)]);
  tagged.writeUInt32BE(tagged.length - 8, tagged.length - 8);
  tagged.write("QTag", tagged.length - 4);
  expect(qmcPayload(tagged, tagged.length + 100).key).toEqual(Buffer.alloc(32, 17));
  tagged.writeUInt32BE(99999, tagged.length - 8);
  expect(() => qmcPayload(tagged, tagged.length + 100)).toThrow();
  expect(() => deriveQmcKey("invalid$secret")).toThrow(expect.objectContaining({ code: "AUDIO_CONVERT_KEY_INVALID" }));
});
